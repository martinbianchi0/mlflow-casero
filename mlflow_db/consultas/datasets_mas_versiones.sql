-- Obtener datasets con mayor cantidad de versiones
SELECT
	D.ID_DATASET,
	D.NOMBRE_DATASET,
	D.DESCRIPCION,
	COUNT(*) AS VERSIONES
FROM
	"DatasetVersion" DV
	JOIN "Dataset" D ON D.ID_DATASET = DV.ID_DATASET
GROUP BY
	D.ID_DATASET,
	D.NOMBRE_DATASET
ORDER BY
	VERSIONES DESC,
	D.NOMBRE_DATASET
LIMIT 10;